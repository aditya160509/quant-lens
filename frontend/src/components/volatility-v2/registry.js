export function getVolatilityV2Feature(featureId) {
  const normalized = String(featureId).replace("feature_", "").replace("feature-", "").padStart(2, "0");
  const feature = VOLATILITY_V2_FEATURES.find((item) => item.id === normalized);
  if (!feature) throw new Error(`Unknown Volatility V2 feature: ${featureId}`);
  return feature;
}
